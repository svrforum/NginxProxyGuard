// Natural Earth leaves three countries-110m features without a numeric id.
// Kosovo has no ISO numeric code, but GeoIP reports it as the user-assigned
// "XK". N. Cyprus and Somaliland have no code of their own, so GeoIP never
// reports them separately; painting them with the CY/SO figures would place
// traffic there that the data does not. They stay unmapped.
const ISO2_BY_NAME = new Map<string, string>([["Kosovo", "XK"]]);

// Resolves a map feature to the alpha-2 country code the API reports. The id
// may be a number or a string, with or without leading zeros.
export function featureToISO2(
  id: string | number | undefined,
  name?: string,
): string | undefined {
  const digits = String(id ?? "");
  if (/^\d+$/.test(digits)) {
    const iso2 = NUMERIC_TO_ISO2[String(Number(digits)).padStart(3, "0")];
    if (iso2) return iso2;
  }
  return name === undefined ? undefined : ISO2_BY_NAME.get(name);
}

